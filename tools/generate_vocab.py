"""Build this sketch's decode table from its tokenizer.

Writes generated/vocab.h: token id -> raw UTF-8 bytes, so the device just
Serial.write()s the bytes of each generated token (llama2.c style).
"""

import argparse
import json
from pathlib import Path

SKETCH = Path(__file__).resolve().parent.parent
ROOT = SKETCH.parent.parent
DEFAULT_TOK = ROOT / "artifacts" / "tinystories" / "tokenizer.json"
DEFAULT_OUT = SKETCH / "generated" / "vocab.h"


def bytes_to_unicode():
    """The GPT-2 / Hugging Face ByteLevel reversible byte to unicode mapping."""
    visible = list(range(0x21, 0x7E + 1))
    visible += list(range(0xA1, 0xAC + 1))
    visible += list(range(0xAE, 0xFF + 1))
    bs, cs, extra = visible[:], visible[:], 0
    for byte in range(256):
        if byte not in bs:
            bs.append(byte)
            cs.append(256 + extra)
            extra += 1
    return dict(zip(bs, (chr(codepoint) for codepoint in cs)))


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--tokenizer", default=DEFAULT_TOK,
                    help="canonical tokenizer.json the header is built from")
    ap.add_argument("--out", default=DEFAULT_OUT, help="header to write")
    args = ap.parse_args()
    TOK, OUT = args.tokenizer, args.out

    # read as plain JSON, so nothing has to be installed: the vocabulary of the BPE model plus the added tokens
    data = json.loads(Path(TOK).read_text(encoding="utf-8"))
    vocab = dict(data["model"]["vocab"])
    for added in data.get("added_tokens", []):
        vocab[added["content"]] = added["id"]
    V = len(vocab)

    # Raw bytes per token, through the ByteLevel symbol map rather than
    # decode(): a token may hold part of a multi-byte character, and decoding
    # such a piece on its own yields U+FFFD instead of the byte. Concatenating
    # the raw bytes of consecutive tokens reconstructs the text exactly, in any
    # language. Special tokens keep their literal text, so the firmware can find
    # the end-of-text id by looking for it in the table.
    symbol_to_byte = {v: k for k, v in bytes_to_unicode().items()}
    id_to_token = {i: t for t, i in vocab.items()}
    assert sorted(id_to_token) == list(range(V)), "token ids must be 0..V-1 without gaps"
    blob = bytearray()
    offs = [0]
    for i in range(V):
        token = id_to_token[i]
        if all(ch in symbol_to_byte for ch in token):
            blob.extend(symbol_to_byte[ch] for ch in token)
        else:
            blob.extend(token.encode("utf-8"))
        offs.append(len(blob))

    # The output directory may not exist in a fresh clone.
    Path(OUT).parent.mkdir(parents=True, exist_ok=True)
    with open(OUT, "w") as f:
        f.write("// Generated by tools/generate_vocab.py\n"
                "// token id -> raw UTF-8 bytes.\n")
        f.write("#ifndef VOCAB_H\n#define VOCAB_H\n")
        f.write(f"#define VOCAB_N {V}\n")
        f.write(f"static const unsigned char VOCAB_BLOB[{len(blob)}] = {{\n")
        for i in range(0, len(blob), 20):
            f.write("  " + ",".join(str(b) for b in blob[i:i+20]) + ",\n")
        f.write("};\n")
        f.write(f"static const int VOCAB_OFF[{len(offs)}] = {{\n")
        for i in range(0, len(offs), 20):
            f.write("  " + ",".join(str(o) for o in offs[i:i+20]) + ",\n")
        f.write("};\n#endif\n")

    print(f"wrote {OUT}: {V} tokens, blob {len(blob)/1024:.0f} KB")



if __name__ == "__main__":
    main()
